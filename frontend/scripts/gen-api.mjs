// Regenerate src/api/schema.d.ts from the backend's OpenAPI schema.
//
//   npm run gen:api                        # backend on http://localhost:8000
//   npm run gen:api -- path/to/openapi.json
//   SFCI_OPENAPI_URL=http://host:8000/openapi.json npm run gen:api
import { writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const source =
  process.argv[2] ?? process.env.SFCI_OPENAPI_URL ?? "http://localhost:8000/openapi.json";
const url = /^https?:\/\//.test(source) ? new URL(source) : pathToFileURL(source);
const out = new URL("../src/api/schema.d.ts", import.meta.url);

const ast = await openapiTS(url);
const header =
  "// Generated by `npm run gen:api` from the backend's OpenAPI schema. Do not edit.\n\n";
await writeFile(out, header + astToString(ast));
console.log(`wrote ${fileURLToPath(out)} from ${source}`);
